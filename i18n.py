def language():
    override = os.environ.get('BILDBLICK_LANGUAGE', '').split('_', 1)[0].split('-', 1)[0].lower()
    if override:
        return 'de' if override == 'de' else 'en'
    for variable in ('LC_ALL', 'LC_MESSAGES', 'LANGUAGE', 'LANG'):
        value = os.environ.get(variable, '').split(':', 1)[0]
        if value and value not in ('C', 'C.UTF-8', 'POSIX'):
            return 'de' if value.split('_', 1)[0].split('-', 1)[0].lower() == 'de' else 'en'
    # English is the release language when a desktop session has no locale.
    return 'en'


def tr(text):
    if not isinstance(text, str) or language() != 'en':
        return text
    if text in _EN:
        return _EN[text]
    # Translate simple labeled values such as "Breite (Pixel)" consistently.
    for de, en in sorted(_EN.items(), key=lambda pair: len(pair[0]), reverse=True):
        if not de:
            continue
        if ' ' in de or any(char in de for char in '·:/?'):
            text = text.replace(de, en)
        else:
            text = re.sub(r'(?<!\w)' + re.escape(de) + r'(?!\w)', en, text)
    return text
